#!/usr/bin/env node
import assert from 'node:assert/strict';
import { createBm25Index, searchBm25 } from '../lib/retrieval/bm25.js';
import { createTokenizer } from '../lib/retrieval/tokenize.js';
import { stage1, stage3 } from '../lib/retrieval/stages.js';
import { expandOneHop } from '../lib/ingest/graph.js';
import { searchVector } from '../lib/embedding/index-store.js';
const tok=createTokenizer({mode:'bigram'});
const docs=[];
for(let i=1;i<=5;i++) docs.push({id:'old-'+i,title:'zzz zzz zzz zzz',summary:'zzz zzz',content:'zzz zzz'});
docs.push({id:'recent-low',title:'zzz',summary:'zzz',content:'zzz'});
const idx=createBm25Index(docs,tok,{});
const all=searchBm25(idx,'zzz',5);
assert.ok(all.length===5 && all.every(x=>String(x[0]).startsWith('old-')),'old top5 baseline');
const allow=id=>String(id)==='recent-low';
const filtered=searchBm25(idx,'zzz',5,{allowId:allow});
assert.ok(filtered.some(x=>String(x[0])==='recent-low'),'recent low included before slice');
assert.ok(filtered.length===1,'only recent allowed');
const ctx={bm25:idx,cardToEpisode:new Map(),episodes:new Map()};
const s1=stage1(ctx,'zzz',5,{allowId:allow});
assert.ok(s1.candidates.some(x=>String(x[0])==='recent-low'),'stage1 passes allowId');
const vf={dim:2,ids:['old-a','recent-b'],flat:new Float32Array([1,1,0.1,0.1])};
const v=searchVector(vf,[1,1],1,{allowId:id=>String(id)==='recent-b'});
assert.ok(v.length===1 && v[0].id==='recent-b','vector passes allowId before topK');
const gctx={edgesByEpisode:new Map([['ep',[{members:[{nodeId:'old-g',weight:1},{nodeId:'recent-g',weight:1}]}]]]),episodes:new Map([['ep',{cardIds:['old-g','recent-g']}]]),cardToEpisode:new Map([['old-g','ep'],['recent-g','ep']])};
const s3=stage3(gctx,{topEpisodes:[['ep',1]]},5,{allowId:id=>String(id)==='recent-g'});
assert.deepEqual(s3.scored.map(x=>x[0]),['recent-g'],'stage3 filters members before scored');
const inc={entityToFacts:new Map([['e',new Set(['old-m','recent-m'])] ]),factToEntities:new Map([['seed',['e']]])};
const ex=expandOneHop([{id:'seed',score:1}],inc,{threshold:100,maxBoostFacts:10,allowId:id=>String(id)==='recent-m'});
assert.ok(ex.some(x=>x.id==='recent-m') && !ex.some(x=>x.id==='old-m'),'graph filters before boost');
console.log('WITHINMS-PRE-DONE checks=7 passed=7 failed=0');
