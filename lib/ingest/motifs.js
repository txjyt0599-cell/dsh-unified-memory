//     这不是语义理解，是「先排除明显不属于生活域的文本」——
//     规则法能做到的极限就在这里，再往上只能靠 LLM（见 extractMotifsLLM）。
//   【阈值】工程词出现 >= 3 个 distinct 就否决。实测工程卡普遍 5+，生活卡 0~1。
const ENGINE_WORDS = [
  '配置', '插件', '索引', '检索', '日志', '进程', '参数', '路径', '端口',
  '部署', '调试', '编译', '构建', '接口', '函数', '变量', '数据库', '缓存',
  '报错', '异常', '崩溃', '内存', '显存', '显卡', '驱动', '启动', '重启',
  '提交', '版本', '仓库', '分支', '测试', '验证', '修复', '验收', '批次',
];
function isEngineContext(text) {
  const s = String(text || '');
  let n = 0;
  for (const w of ENGINE_WORDS) { if (s.indexOf(w) >= 0) n++; if (n >= 3) return true; }
  return false;
}

// [2026-11-04 by Phoebe] LIFE_MOTIFS 支持第 3 项「否决函数」：
//   规则命中后再跑一次 guard(s)，返回 false 则丢弃。
//   用于「字面命中但语境不对」的场景（如「看视频插件抽帧」）。
const ALL = [].concat(
  FAULT_MOTIFS.map(function (x) { return { re: x[0], motif: x[1], kind: 'fault' }; }),
  MOOD_MOTIFS.map(function (x) { return { re: x[0], motif: x[1], kind: 'mood' }; }),
  LIFE_MOTIFS.map(function (x) { return { re: x[0], motif: x[1], kind: 'life', guard: x[2] || null }; })
);

/**
 * 从一段文本提取 0~3 个情境骨架。
 * @param {string} text  卡片的 title + content
 * @param {object} opts  { max: 3 }
 * @returns {string[]}   motifs 数组（可能为空 = 这张卡没有可抽象的情境）
 */
export function extractMotifs(text, opts) {
  const o = opts || {};
  const max = Number(o.max) || 3;
  const s = String(text || '');
  if (!s.trim()) return [];

  const found = [];
  const seen = new Set();
  // [2026-11-04 by Phoebe] 生活类标签额外加「工程语境否决」：
  //   工程词密度高的卡一律不打 life 标签（详见 ENGINE_WORDS 上方注释）。
  //   只影响 kind==='life' 的规则，故障/情绪类不受影响 —— 那些本来就该出现在工程卡里。
  const engineCtx = isEngineContext(s);
  for (const rule of ALL) {
    if (found.length >= max) break;
    if (seen.has(rule.motif)) continue;
    if (rule.kind === 'life' && engineCtx) continue;   // ← 新增否决
    try {
      if (rule.re.test(s)) {
        // [2026-11-04] 规则自带否决函数时再跑一次（语境不对就丢弃）
        if (typeof rule.guard === 'function') {
          try { if (!rule.guard(s)) continue; } catch (e2) { continue; }
        }
        found.push(rule.motif);
        seen.add(rule.motif);
      }
    } catch (e) {}
  }
  return found;
}

/** 判断一张卡是否值得有 motifs（太短的、纯流水账的没有情境） */
export function shouldHaveMotifs(text) {
  const s = String(text || '').trim();
  if (s.length < 12) return false;
  if (/^(好的|收到|继续|嗯|开始吧|可以)[。！]?$/.test(s)) return false;
  return true;
}

export default { extractMotifs, shouldHaveMotifs };


